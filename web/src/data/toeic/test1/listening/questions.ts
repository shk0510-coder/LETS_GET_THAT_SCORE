function buildQuestion(raw: RawQuestion): Question {
  const part = partForQuestion(raw.id);
  const choiceCount = part === 2 ? 3 : 4;

  const question: Question = {
    id: raw.id,
    part,
    choiceCount,
    answer: raw.answer,
    script: raw.script,
    explanation: raw.explanation,
  };

  if (raw.promptText) {
    question.promptText = raw.promptText;
  }
  if (raw.options) {
    question.options = raw.options;
  }

  if (part === 1) {
    question.photoSrc = `/toeic/test1/part1/q${String(raw.id).padStart(3, "0")}.jpg`;
  }

  if (part === 3 || part === 4) {
    const setStart = setStartFor(raw.id, part);
    if (GRAPHIC_SET_STARTS.has(setStart)) {
      question.graphicSrc = `/toeic/test1/graphics/q${String(setStart).padStart(3, "0")}.png`;
    }
  }

  return question;
}

export const QUESTIONS: Question[] = RAW_QUESTIONS.map(buildQuestion);

export function getQuestion(id: number): Question | undefined {
  return QUESTIONS.find((q) => q.id === id);
}

